// run executes a module and returns what it said through Сообщить().
func run(t *testing.T, src string) (string, error) {
	t.Helper()
	it := New()
	it.Now = func() time.Time { return time.Date(2026, 10, 25, 14, 30, 0, 0, time.UTC) }
	var out []string
	it.Message = func(s string) { out = append(out, s) }
	_, err := it.Run("Тест", src)
	return strings.Join(out, "\n"), err
}

