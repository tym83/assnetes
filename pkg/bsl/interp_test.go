func TestErrors(t *testing.T) {
	cases := []struct{ src, want string }{
		{`А = Б + 1;`, "{Тест(1)}: Переменная не определена (Б)"},
		{`Нету();`, "Процедура или функция с указанным именем не определена (Нету)"},
		{`Процедура П() КонецПроцедуры А = П();`, "Использование процедуры в качестве функции (П)"},
		{`М = Новый Массив; М[5] = 1;`, "Индекс находится за границами диапазона"},
		{`Если 1 Тогда КонецЕсли;`, "Преобразование значения к типу Булево не может быть выполнено"},
		{`Выполнить("Сообщить(1)");`, "безопасный режим"},
		{`А = 1`, ""},
		{"Если Истина Тогда\nА = 1;\n", "Синтаксическая ошибка"},
		{`Перейти ~Метка;`, "у нас не 7.7"},
		{`А = Новый Отчёт;`, "Тип не определен (Отчёт)"},
	}
	for _, c := range cases {
		_, err := run(t, c.src)
		if c.want == "" {
			if err != nil {
				t.Errorf("%q: unexpected error %v", c.src, err)
			}
			continue
		}
		if err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%q: got %v, want %q", c.src, err, c.want)
		}
	}
}

func TestEventHandlerSetsCancel(t *testing.T) {
	it := New()
	s, err := it.Run("Обработка", `
&Обработка(Вид = "Infobase", Владеет = "StatefulSet")
Процедура ОбработкаПроведения(Объект, Отказ) Экспорт
	Если НЕ ЗначениеЗаполнено(Объект.Кластер) Тогда
		Отказ = Истина;
	КонецЕсли;
КонецПроцедуры`)
	if err != nil {
		t.Fatal(err)
	}
	m := s.Module().Method("обработкапроведения")
	a := m.Annotation("Обработка")
	if a == nil {
		t.Fatal("no annotation")
	}
	if v, _ := a.Param("Вид", -1); v != "Infobase" {
		t.Fatalf("Вид = %v", v)
	}
	obj := NewStructure()
	obj.Insert("Кластер", "")
	cancel := &Ref{V: false}
	if _, err := s.CallRefs("ОбработкаПроведения", []*Ref{{V: obj}, cancel}); err != nil {
		t.Fatal(err)
	}
	if cancel.V != true {
		t.Fatalf("Отказ = %v", cancel.V)
	}
}

